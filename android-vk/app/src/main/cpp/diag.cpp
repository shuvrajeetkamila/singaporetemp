const Glyph* findGlyph(char c) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    for (const Glyph& g : kGlyphs) {
        if (g.ch == c) return &g;
    }
    return nullptr;
}

constexpr int kCellW = 6;  // 5 columns plus a gap
constexpr int kCellH = 8;  // 7 rows plus a gap

void fillRect(const PixelBuffer& b, int x0, int y0, int w, int h, uint32_t colour) {
    for (int y = y0; y < y0 + h; ++y) {
        if (y < 0 || y >= b.height) continue;
        uint32_t* row = b.px + static_cast<size_t>(y) * static_cast<size_t>(b.stride);
        for (int x = x0; x < x0 + w; ++x) {
            if (x >= 0 && x < b.width) row[x] = colour;
        }
    }
}

