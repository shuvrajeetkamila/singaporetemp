const char* const* glyphRows(char c) {
    const Glyph* g = findGlyph(c);
    return g ? g->rows : nullptr;
}

bool hasGlyph(char c) {
    return findGlyph(c) != nullptr;
}

void fillPixels(const PixelBuffer& b, uint32_t colour) {
    if (!b.px) return;
    for (int y = 0; y < b.height; ++y) {
        uint32_t* row = b.px + static_cast<size_t>(y) * static_cast<size_t>(b.stride);
        for (int x = 0; x < b.width; ++x) row[x] = colour;
    }
}

int drawTextLines(const PixelBuffer& b, const char* const* lines, int count, uint32_t colour) {
    if (!b.px || !lines || count <= 0 || b.width <= 0 || b.height <= 0) return 0;

    int longest = 1;
    for (int i = 0; i < count; ++i) {
        int len = 0;
        while (lines[i] && lines[i][len]) ++len;
        if (len > longest) longest = len;
    }

    // Largest integer scale that fits the longest line in the width and all lines in the height.
    const int margin = b.width / 40 > 4 ? b.width / 40 : 4;
    const int byWidth = (b.width - 2 * margin) / (longest * kCellW);
    const int byHeight = (b.height - 2 * margin) / (count * kCellH);
    int scale = byWidth < byHeight ? byWidth : byHeight;
    if (scale < 1) return 0;
    if (scale > 24) scale = 24;

    for (int i = 0; i < count; ++i) {
        const char* text = lines[i];
        if (!text) continue;
        const int y0 = margin + i * kCellH * scale;
        for (int k = 0; text[k]; ++k) {
            const Glyph* g = findGlyph(text[k]);
            if (!g) continue;
            const int x0 = margin + k * kCellW * scale;
            for (int r = 0; r < 7; ++r) {
                for (int c = 0; c < 5; ++c) {
                    if (g->rows[r][c] == '#') {
                        fillRect(b, x0 + c * scale, y0 + r * scale, scale, scale, colour);
                    }
                }
            }
        }
    }
    return scale;
}
